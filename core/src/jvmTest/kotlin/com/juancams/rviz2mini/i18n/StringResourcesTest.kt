package com.juancams.rviz2mini.i18n

import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * The user texts (the strings XML files of app/src/main/res/values and values-es, shared by both apps): every key the code asks for exists in
 * English, Spanish has every English key, and both versions take the same format arguments (a missing %2$s would
 * crash String.format at run time).
 */
class StringResourcesTest {
    private val root = listOf(File(".."), File(".")).first { File(it, "app/src/main/res/values").isDirectory }
    private val keyRe = Regex("""<string name="([a-zA-Z0-9_]+)"[^>]*>(.*?)</string>""", RegexOption.DOT_MATCHES_ALL)
    private val argRe = Regex("""%(\d+)\$[-#+ 0,(]*\d*(?:\.\d+)?[a-zA-Z]""")

    private fun entries(dir: String) = File(root, "app/src/main/res/$dir").listFiles { f -> f.name.endsWith(".xml") }.orEmpty()
        .flatMap { f -> keyRe.findAll(f.readText()).toList() }

    private fun strings(dir: String): Map<String, String> = entries(dir).associate { it.groupValues[1] to it.groupValues[2] }

    /** Not translated on purpose (translatable="false": the brand, "0.5×"...). */
    private val untranslatable = entries("values").filter { "translatable=\"false\"" in it.value }.map { it.groupValues[1] }.toSet()

    /** Generated by the Google services plugin from google-services.json (not in the sources). */
    private val generated = setOf("default_web_client_id", "gcm_defaultSenderId", "google_api_key", "google_app_id", "project_id")

    private val en = strings("values")
    private val es = strings("values-es")

    @Test fun spanishHasEveryKey() {
        val missing = en.keys - es.keys - untranslatable
        assertTrue("missing in values-es: ${missing.sorted()}", missing.isEmpty())
        val extra = es.keys - en.keys
        assertTrue("only in values-es (no English): ${extra.sorted()}", extra.isEmpty())
    }

    @Test fun theDesktopLoadsEveryStringsFile() {
        val files = File(root, "app/src/main/res/values").listFiles { f -> f.name.startsWith("strings") && f.name.endsWith(".xml") }.orEmpty().map { it.name }
        val loaded = files.filter { it in XmlStrings.FILES }
        assertTrue("strings files the desktop does not load (add them to XmlStrings.FILES): ${files - loaded.toSet()}", loaded.size == files.size)
    }

    @Test fun sameFormatArguments() {
        val bad = en.keys.intersect(es.keys).filter { k ->
            argRe.findAll(en[k]!!).map { it.groupValues[1] }.toSet() != argRe.findAll(es[k]!!).map { it.groupValues[1] }.toSet()
        }
        assertTrue("different %N\$ arguments in English and Spanish: ${bad.sorted()}", bad.isEmpty())
    }

    @Test fun everyKeyUsedByTheCodeExists() {
        val used = HashSet<String>()
        val call = Regex("""\btr\("([a-z0-9_]+)"""")
        val res = Regex("""R\.string\.([a-zA-Z0-9_]+)""")
        for (dir in listOf("core/src/jvmMain", "ui/src/main", "rviz3d/src/main", "desktopApp/src/jvmMain", "app/src/main/java")) {
            File(root, dir).walkTopDown().filter { it.isFile && it.extension == "kt" }.forEach { f ->
                // Without comments (they quote example keys).
                val text = f.readText().replace(Regex("""/\*.*?\*/""", RegexOption.DOT_MATCHES_ALL), "").replace(Regex("""//[^\n]*"""), "")
                call.findAll(text).forEach { used += it.groupValues[1] }
                res.findAll(text).forEach { used += it.groupValues[1] }
            }
        }
        val missing = used - en.keys - generated
        assertTrue("texts asked for by the code but not in values/strings*.xml: ${missing.sorted()}", missing.isEmpty())
    }
}
